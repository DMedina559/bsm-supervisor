"""Refresh a stopped managed unit and its private environment."""

import os
import subprocess
import tempfile
import uuid
from pathlib import Path

from .activation import service_unit
from .checkpoint_files import sync_directory
from .config import Config
from .service import ServiceError, SystemdService
from .service_environment import write_environment
from .store import Store

UNIT_DIRECTORY = Path("/etc/systemd/system")


def publish(path: Path, data: bytes, mode: int) -> None:
    """Replace one regular file atomically and flush its directory."""
    descriptor, name = tempfile.mkstemp(prefix=".supervisor-", dir=path.parent)
    temporary = Path(name)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            os.fchmod(stream.fileno(), mode)
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
        sync_directory(path.parent)
    finally:
        temporary.unlink(missing_ok=True)


def refresh(config: Config, store: Store, user: str) -> None:
    """Verify, back up, and replace a stopped supervisor-owned unit."""
    if os.geteuid() != 0:
        raise ValueError("unit-refresh requires root")
    rendered = service_unit(config, user)
    destination = UNIT_DIRECTORY / config.service_unit
    environment = config.state_dir / "bsm-runtime.env"
    with store.lock():
        service = SystemdService(config)
        state = service.status()
        if (
            state.get("ActiveState") not in ("inactive", "failed")
            or state.get("MainPID") != "0"
            or state.get("Job")
        ):
            raise ValueError("Stop BSM gracefully before running unit-refresh")
        if destination.is_symlink() or not destination.is_file():
            raise ValueError("unit-refresh requires a regular existing managed unit")
        original = destination.read_bytes()
        if b"Description=Bedrock Server Manager (BSM Supervisor)\n" not in original:
            raise ValueError(
                "Refusing to replace a unit not generated by the supervisor"
            )
        if environment.is_symlink() or (
            environment.exists() and not environment.is_file()
        ):
            raise ValueError("Managed environment must be a regular file")
        with tempfile.TemporaryDirectory(prefix="bsm-unit-") as temporary:
            candidate = Path(temporary) / config.service_unit
            candidate.write_text(rendered)
            try:
                result = subprocess.run(
                    ["/usr/bin/systemd-analyze", "verify", "--man=no", str(candidate)],
                    capture_output=True,
                    text=True,
                    timeout=config.service_timeout,
                    check=False,
                )
            except subprocess.TimeoutExpired as error:
                raise ServiceError(
                    "Unit verification timed out; unit unchanged"
                ) from error
            if result.returncode:
                raise ServiceError("Unit verification failed; unit unchanged")
        with store.mutation(
            "service:unit-refresh", preserve_on_error=True
        ) as operation:
            backups = config.state_dir / "service-backups"
            backups.mkdir(mode=0o700, exist_ok=True)
            backup = backups / uuid.uuid4().hex
            backup.mkdir(mode=0o700)
            publish(backup / config.service_unit, original, 0o600)
            if environment.exists():
                publish(backup / "bsm-runtime.env", environment.read_bytes(), 0o600)
            store.note(operation, "Previous managed files saved in " + str(backup))
            write_environment(config)
            publish(destination, rendered.encode(), 0o644)
            service.reload_units()
            if state.get("ActiveState") == "failed":
                service.reset_failed()
